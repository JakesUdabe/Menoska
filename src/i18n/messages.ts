function setPath(target: Record<string, unknown>, path: string, value: string) {
  const parts = path.split(".");
  let cur = target;
  for (let i = 0; i < parts.length - 1; i += 1) {
    const key = parts[i];
    const next = cur[key];
    if (!next || typeof next !== "object") {
      cur[key] = {};
    }
    cur = cur[key] as Record<string, unknown>;
  }
  cur[parts[parts.length - 1]] = value;
}

function mergeMissing(target: Record<string, unknown>, extra: Record<string, unknown>) {
  for (const [key, value] of Object.entries(extra)) {
    const current = target[key];
    if (value && typeof value === "object" && !Array.isArray(value)) {
      if (typeof current === "string") continue;
      if (!current || typeof current !== "object") target[key] = {};
      mergeMissing(target[key] as Record<string, unknown>, value as Record<string, unknown>);
      continue;
    }
    if (!(key in target)) target[key] = value;
  }
}

